import {z} from 'zod';
import {zColor} from '@remotion/zod-types';

// Everything the video says lives here, so a requirement can change
// without touching the animation code.
export const traceChainSchema = z.object({
  tagId: z.string(),
  colors: z.object({
    bg: zColor(),
    srs: zColor(),
    fr: zColor(),
    tasks: zColor(),
    test: zColor(),
    commit: zColor(),
    ok: zColor(),
    text: zColor(),
    muted: zColor(),
    panel: zColor(),
    border: zColor(),
  }),
  sound: z.boolean(),
  title: z.string(),
  srs: z.object({
    label: z.string(),
    text: z.string(),
    highlights: z.array(z.string()),
    revLabel: z.string(),
  }),
  spec: z.object({
    tab: z.string(),
    chips: z.array(z.string()),
    code: z.string(),
    clarify: z.string(),
    ccbLabel: z.string(),
    resolved: z.string(),
  }),
  plan: z.object({
    tab: z.string(),
    code: z.string(),
    bannerLabel: z.string(),
    bannerItems: z.array(z.string()),
  }),
  tasks: z.object({
    tab: z.string(),
    code: z.string(),
    focusTaskId: z.string(),
  }),
  terminal: z.object({
    title: z.string(),
    testCommand: z.string(),
    testName: z.string(),
    testRef: z.string(),
    testStats: z.string(),
    commitCommand: z.string(),
    commitOutput: z.string(),
    commitHash: z.string(),
    grepCommand: z.string(),
    grepResults: z.array(z.string()),
  }),
  chain: z.object({
    pills: z.array(z.object({label: z.string(), color: zColor()})),
    caption: z.string(),
  }),
  timing: z.object({
    // Scene boundaries (absolute frames).
    scenes: z.array(z.number()).length(9),
    titleDockFrame: z.number(),
    typeSpeed: z.number(),
    underlineFrame: z.number(),
    ccbFrame: z.number(),
    strikeFrame: z.number(),
    bannerFrame: z.number(),
    checkStartFrame: z.number(),
    checkInterval: z.number(),
    pillInterval: z.number(),
    captionFrame: z.number(),
    fadeOutFrame: z.number(),
  }),
});

